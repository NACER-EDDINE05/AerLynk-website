"use client";

import { useEffect, useRef, useState } from "react";

type Line = { text: string; tone: "cmd" | "ok" | "info" | "flow" };

const SCRIPT: Line[] = [
  { text: "$ aerlynk send --files ~/exports/quarterly-report.pdf", tone: "cmd" },
  { text: "✓ session created · token 9f3c…a2 (256-bit, CSPRNG)", tone: "ok" },
  { text: "✓ AES-256 key generated by the OS · never persisted", tone: "ok" },
  { text: "✓ server bound to 192.168.1.24:52841 · LAN only", tone: "ok" },
  { text: "→ scan the QR — the key rides in the URL fragment, never the wire", tone: "flow" },
  { text: "✓ phone paired · code K7-M4 verified on both screens", tone: "ok" },
  { text: "⟶ chunk 42/118 · 42.0/118.0 MiB · 31 MB/s · tag ok", tone: "flow" },
  { text: "✓ transfer sealed · 0 bytes unencrypted on the network", tone: "ok" },
  { text: "· session expires after 10 quiet minutes", tone: "info" },
];

const TONE_CLASS: Record<Line["tone"], string> = {
  cmd: "text-ink",
  ok: "text-mint",
  info: "text-ink-3",
  flow: "text-accent-2",
};

/**
 * A live session log that types itself when scrolled into view.
 * Honors prefers-reduced-motion by rendering the full transcript instantly.
 */
export function Terminal() {
  const ref = useRef<HTMLDivElement>(null);
  const [lineIdx, setLineIdx] = useState(0);
  const [charIdx, setCharIdx] = useState(0);
  const [started, setStarted] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      setStarted(true);
      setLineIdx(SCRIPT.length);
      return;
    }
    const io = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) {
            setStarted(true);
            io.disconnect();
          }
        }
      },
      { threshold: 0.35 },
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);

  useEffect(() => {
    if (!started || lineIdx >= SCRIPT.length) return;
    const line = SCRIPT[lineIdx];
    if (charIdx < line.text.length) {
      const t = setTimeout(() => setCharIdx((c) => c + 1), line.tone === "cmd" ? 34 : 9);
      return () => clearTimeout(t);
    }
    const t = setTimeout(() => {
      setLineIdx((i) => i + 1);
      setCharIdx(0);
    }, line.tone === "cmd" ? 260 : 130);
    return () => clearTimeout(t);
  }, [started, lineIdx, charIdx]);

  const done = lineIdx >= SCRIPT.length;

  return (
    <div
      ref={ref}
      className="glass-deep rounded-2xl p-4 font-mono text-[11px] leading-6 sm:p-5 sm:text-[12.5px] sm:leading-7"
    >
      <div className="mb-3 flex items-center gap-2 border-b border-white/8 pb-3 text-[11px] text-ink-3">
        <span className="h-2.5 w-2.5 rounded-full bg-coral/80" aria-hidden />
        session log
        <span className="ml-auto font-mono text-[10px]">tail -f aerlynk</span>
      </div>
      <div role="img" aria-label="AerLynk terminal session log, animating a file transfer">
        {SCRIPT.slice(0, Math.min(lineIdx + 1, SCRIPT.length)).map((line, i) => (
          <div key={i} className={`break-words ${TONE_CLASS[line.tone]}`}>
            {i === lineIdx && !done ? line.text.slice(0, charIdx) : line.text}
            {i === lineIdx && !done && <span className="caret ml-0.5" aria-hidden />}
          </div>
        ))}
        {done && (
          <div className="text-ink-3">
            $ <span className="caret" aria-hidden />
          </div>
        )}
      </div>
    </div>
  );
}
